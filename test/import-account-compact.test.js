const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')
const markup = read('miniprogram/packages/finance/pages/import-workbench/index.wxml')
const style = read('miniprogram/packages/finance/pages/import-workbench/index.wxss')
const start = markup.indexOf(`<view wx:if="{{item.inline && item.choiceValue === 'create'}}" class="account-decision-row account-decision-create account-create-line">`)
const end = markup.indexOf('<button wx:if="{{!item.inline}}" class="account-decision-row account-transfer-control"', start)
const row = markup.slice(start, end)

test('账户标题始终显示当前账户或操作，并带下拉箭头', () => {
  assert.ok(start >= 0 && end > start)
  assert.match(markup, /class="account-title-trigger"/)
  assert.match(row, />新建账户<\/text>/)
  assert.match(markup, /\{\{item\.choiceName\}\}/)
  assert.match(markup, /class="account-state-tag/)
  assert.match(markup, /account-state-tag-pending/)
  assert.match(markup, /account-state-tag-done/)
})

test('来源单独一行，多来源用平台文字与分别确认，主笔数承接去重标记', () => {
  assert.match(markup, /class="account-source-line[ "]/)
  assert.match(markup, /来源：\{\{item\.sourceLabel\}\}/)
  // 来源名缺失时不能拿问题类型名冒充，改成「来源未识别」并带上交易对方。
  assert.match(markup, /来源未识别/)
  assert.match(markup, /item\.sourceHint/)
  assert.match(markup, /item\.inline && item\.groupId/)
  assert.match(markup, /来源：\{\{item\.groupSourceText\}\}/)
  assert.doesNotMatch(markup, /item\.groupSourceChips|item\.groupCountNote/)
  assert.match(markup, /wx:if="\{\{item\.groupDeduplicated\}\}"[^>]*>去重后<\/text>/)
  assert.match(markup, /\{\{item\.accountSeparatedCountNote \|\| '这组账单已拆开'\}\}/)
  const grouping = read('miniprogram/packages/finance/pages/import-workbench/account-display-groups.js')
  assert.match(grouping, /可能同一张卡/)
  assert.match(grouping, /已选择同一账户/)
  assert.match(markup, /bindtap="separateAccountGroup"/)
  assert.match(markup, /恢复合并/)
})

test('新建账户：选择、名称、类型、状态都在同一行里', () => {
  const trigger = row.indexOf('account-title-trigger')
  const name = row.indexOf('account-compact-name')
  const type = row.indexOf('account-compact-type')
  assert.ok(trigger >= 0 && trigger < name && name < type, '三者按进入顺序排在同一个容器')
  assert.ok(row.indexOf('account-state-tag') > type, '状态标签收在同一行末尾')
  assert.equal((row.match(/class="account-decision-divider"/g) || []).length, 2)
  assert.match(style, /\.account-create-line\s*\{[^}]*width:\s*100%;/)
  assert.doesNotMatch(row, /account-mode-trigger/)
  assert.doesNotMatch(markup, /account-mode-trigger/)
  assert.match(row, /maxlength="32" value="\{\{item\.draftName\}\}"/)
  assert.match(row, /bindinput="bindAccountDraftName"[^>]*disabled="\{\{accountStepBusy\}\}"/)
  assert.match(row, /range="\{\{item\.typeOptions\}\}" range-key="label" value="\{\{item\.draftTypeOptionIndex\}\}"/)
  assert.match(row, /bindchange="changeAccountDraftType" disabled="\{\{accountStepBusy\}\}"/)
  assert.match(row, /aria-label="\{\{item\.label\}\}的新账户名称"/)
  assert.match(row, /aria-label="\{\{item\.label\}\}的账户类型/)
  const groupStart = markup.indexOf('<view wx:if="{{item.inline && item.groupId}}"')
  const groupEnd = markup.indexOf('<view wx:if="{{item.inline && !item.groupId}}"', groupStart)
  assert.ok(groupStart >= 0 && groupEnd > groupStart)
  const grouped = markup.slice(groupStart, groupEnd)
  assert.match(grouped, /wx:if="\{\{item\.choiceValue === 'create' && item\.memberCount > 0\}\}"[^>]*bindtap="openAccountRecords"/,
    '新建联合卡也有可达的交易入口，不能只给非新建或单来源卡显示笔数')
  assert.match(grouped, /data-id="\{\{item\.issueId\}\}"[^>]*bindtap="openAccountRecords"/)
})

test('类型仍完整可读，名称可编辑且不缩字，保留至少88rpx触控高度', () => {
  assert.match(style, /\.account-decision-create \.account-mode-control,[\s\S]*?\.account-decision-create \.account-compact-type-control\s*\{[^}]*min-height:\s*88rpx;/)
  assert.match(style, /\.account-decision-create \.account-compact-type-value\s*\{[^}]*white-space:\s*normal;/)
  assert.match(row, /aria-label="\{\{item\.label\}\}的账户类型，\{\{item\.draftTypeLabel\}\}"/)
  assert.match(row, /class="account-compact-type-value">\{\{item\.draftTypeLabel\}\}<\/text>/)
  assert.doesNotMatch(row, /type="hidden"|hidden="true"/)
  assert.match(row, /account-compact-type-locked/)
  // 锁定的类型不给下拉箭头：只看 locked 到状态标签之间那一段。
  const lockedSection = row.slice(row.indexOf('account-compact-type-locked'), row.indexOf('account-state-tag'))
  assert.doesNotMatch(lockedSection, /account-dropdown-chevron/)
})

test('卡片不再有逐项确认按钮，确认统一到底部', () => {
  assert.doesNotMatch(markup, /account-confirm-row/)
  assert.doesNotMatch(markup, /class="account-summary-row"/)
  assert.doesNotMatch(markup, /建议账户，可更改/)
  assert.doesNotMatch(markup, /本批新建账户，可更改/)
  assert.doesNotMatch(markup, /bindtap="completeAccountMapping"/)
  assert.match(markup, /class="account-confirm-note"/)
})

test('底部区分待处理与可确认，批量确认交给底栏', () => {
  assert.match(markup, /accountStepSummary\.unselected > 0/)
  assert.match(markup, /还有 \{\{accountStepSummary\.unselected\}\} 项待处理/)
  assert.match(markup, /accountStepSummary\.batchable > 0/)
  assert.match(markup, /确认剩余 \{\{accountStepSummary\.batchable\}\} 项/)
  assert.match(markup, /accountStepSummary\.batchNote/)
  assert.match(markup, /class="account-batch-sub"/)
  assert.match(read('miniprogram/packages/finance/pages/import-workbench/account-review.js'), /本批将新建 /)
  assert.match(markup, /bindtap="confirmAllAccountMappings"/)
  assert.match(markup, /下一步：整理账目/)
  assert.match(style, /\.account-source-text\s*\{[^}]*font-size:/)
  assert.match(style, /\.account-state-tag\s*\{[^}]*border-radius:/)
})
