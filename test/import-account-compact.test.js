const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8')
const markup = read('miniprogram/packages/finance/pages/import-workbench/index.wxml')
const style = read('miniprogram/packages/finance/pages/import-workbench/index.wxss')
const start = markup.indexOf('<view wx:if="{{item.inline && !item.choiceMatchesTitle}}" class="account-decision-row')
const end = markup.indexOf('<button wx:elif="{{!item.inline}}" class="account-decision-row account-transfer-control"', start)
const row = markup.slice(start, end)

test('新建名称与标题不同才显示处理行，原选择、名称输入、类型及忙碌门禁不变', () => {
  assert.ok(start >= 0 && end > start)
  assert.match(row, /account-mode-trigger/)
  assert.match(row, /account-compact-name/)
  assert.match(row, /account-compact-type/)
  assert.equal((row.match(/class="account-decision-divider"/g) || []).length, 2)
  assert.doesNotMatch(row, /account-create-fields|account-create-field|account-field-label/)
  assert.match(style, /\.account-decision-create\s*\{[^}]*display:\s*flex;[^}]*flex-wrap:\s*nowrap;/)
  assert.match(style, /\.account-decision-create \.account-compact-name\s*\{[^}]*min-width:\s*0;[^}]*flex:\s*1 1 0;/)
})

test('三项只改变排版，原账户选择、名称输入、类型及忙碌门禁不变', () => {
  assert.match(row, /data-id="{{item.issueId}}" bindtap="openAccountChoice" disabled="{{accountStepBusy}}"/)
  assert.match(row, /maxlength="32" value="{{item.draftName}}"/)
  assert.match(row, /bindinput="bindAccountDraftName"[^>]*disabled="{{accountStepBusy}}"/)
  assert.match(row, /range="{{item.typeOptions}}" range-key="label" value="{{item.draftTypeOptionIndex}}"/)
  assert.match(row, /bindchange="changeAccountDraftType" disabled="{{accountStepBusy}}"/)
  assert.match(row, /aria-label="{{item.label}}的新账户名称"/)
  assert.match(row, /aria-label="{{item.label}}的账户类型/)
  assert.match(markup, /已确认 {{accountStepSummary.displayConfirmed}}/)
  assert.match(markup, /建议账户，可更改/)
  assert.match(markup, /本批新建账户，可更改/)
  assert.doesNotMatch(markup, /account-pending-label/)
})

test('新建编辑行统一白底，确认按钮独立，已确认项可更改', () => {
  assert.match(style, /\.account-mode-trigger\.account-mode-trigger-pending\[disabled\]\s*\{[^}]*background:\s*var\(--ui-surface\) !important;/)
  assert.match(markup, /account-confirm-row/)
  assert.match(markup, /!item.needsConfirmation/)
  assert.match(markup, /account-summary-text/)
  assert.match(markup, /class="account-change"/)
  assert.match(markup, /（剩 /)
})

test('类型仍完整可读，名称可编辑且不缩字，保留至少88rpx触控高度', () => {
  assert.match(style, /\.account-decision-create \.account-mode-control,[\s\S]*?\.account-decision-create \.account-compact-type-control\s*\{[^}]*min-height:\s*88rpx;/)
  assert.match(style, /\.account-decision-create \.account-compact-type-value\s*\{[^}]*white-space:\s*normal;/)
  assert.match(row, /aria-label="{{item.label}}的账户类型，{{item.draftTypeLabel}}"/)
  assert.match(row, /class="account-compact-type-value">{{item.draftTypeLabel}}<\/text>/)
  assert.doesNotMatch(row, /type="hidden"|hidden="true"/)
})

test('选中的就是标题账户时不再重复渲染下拉框，标题本身是更改入口', () => {
  assert.doesNotMatch(markup, /核对建议，不合适可更改/)
  assert.match(markup, /<view wx:if="\{\{item\.inline && item\.needsConfirmation\}\}" class="account-title-trigger" data-id="\{\{item\.issueId\}\}" bindtap="openAccountChoice" aria-role="button" aria-disabled="\{\{accountStepBusy\}\}"[\s\S]*?<text class="account-proof-title">\{\{item\.label\}\}<\/text><view class="account-dropdown-chevron"><\/view><\/view>/)
  assert.doesNotMatch(markup, /<button[^>]*class="account-title-trigger"/)
  assert.match(markup, /<text wx:else class="account-proof-title">\{\{item\.label\}\}<\/text>/)
  assert.match(markup, /<view wx:if="\{\{item\.inline && !item\.choiceMatchesTitle\}\}" class="account-decision-row/)
  assert.match(markup, /建议账户，可更改/)
  assert.doesNotMatch(markup, /已按名称、银行和尾号推荐，请核对。/)
  assert.match(style, /\.account-title-trigger\s*\{[^}]*display:\s*inline-flex;[^}]*background:\s*transparent;/)
  // 原生 button 自带左右内边距；这里必须用 view 让标题从卡片左边界开始。
  assert.match(style, /\.account-title-trigger\s*\{[^}]*margin:\s*0;[^}]*padding:\s*0;/)
  assert.match(style, /\.account-title-trigger\s*\{[^}]*flex:\s*0 0 auto;[^}]*width:\s*auto;/)
  assert.match(style, /\.account-title-trigger\s*\{[^}]*justify-content:\s*flex-start;[^}]*text-align:\s*left;/)
  assert.match(style, /\.account-proof-title-line\s*\{[^}]*justify-content:\s*flex-start;/)
  assert.doesNotMatch(style, /\.account-title-trigger\[disabled\]/)
})

test('外部入口只留在弹层，单类型锁定下拉，批量确认交给底栏', () => {
  assert.doesNotMatch(markup, /不是我的账户？可在上方改选/)
  assert.doesNotMatch(markup, /account-batch-row|account-batch-action|account-batch-copy/)
  assert.doesNotMatch(style, /\.account-batch-(row|action|copy|note)\b/)
  assert.match(markup, /<button wx:if="\{\{accountStepSummary\.suggested > 0\}\}" class="primary-button stage-primary account-batch-primary" bindtap="confirmAllAccountMappings"[\s\S]*?<text class="account-batch-label">确认剩余 \{\{accountStepSummary\.suggested\}\} 项<\/text>/)
  assert.match(markup, /<text wx:if="\{\{accountStepSummary\.suggestedCreate > 0\}\}" class="account-batch-sub">其中 \{\{accountStepSummary\.suggestedCreate\}\} 项会新建账户<\/text><\/button>/)
  assert.match(markup, /<button wx:else class="primary-button stage-primary" data-step="3" bindtap="goToStep"[\s\S]*?>下一步：整理账目/)
  assert.match(style, /\.stage-navigation \.account-batch-primary\s*\{[^}]*flex-direction:\s*column;/)
  assert.match(style, /\.account-batch-sub\s*\{[^}]*font-size:/)
  assert.match(markup, /item\.groupId \? '确认 ' \+ item\.memberCount \+ ' 笔' : '确认'/)
  assert.match(markup, /<text wx:if="\{\{item\.groupCandidate\}\}" class="account-group-hint">可能同一张卡<\/text>\s*<button class="account-group-separate"/)
  assert.match(markup, /item\.suggestedExisting && !item\.groupId/)
  assert.match(style, /\.account-group-hint\s*\{[^}]*margin-left:\s*auto;/)
  assert.match(style, /\.account-group-separate\s*\{[^}]*width:\s*auto;/)
  assert.match(markup, /class="account-recheck-note"><text>\{\{item\.ownershipNote\}\}<\/text>/)
  assert.match(row, /wx:if="\{\{!item\.typeLocked\}\}"/)
  assert.match(row, /account-compact-type-locked/)
  assert.doesNotMatch(row, /account-compact-type-locked[\s\S]*?account-dropdown-chevron/)
  assert.match(style, /\.account-compact-type-locked \.account-compact-type-value\s*\{[^}]*color:/)
  assert.match(style, /\.account-recheck-note\s*\{[^}]*line-height:/)
})
