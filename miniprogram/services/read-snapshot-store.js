const { READ_POLICIES } = require('./read-policy')
const { validMetadata } = require('./read-metadata')
const { bytes } = require('./read-observer')
const KEY = 'catledger_read_snapshots_v1'
// 账单资料扩展了账户读取结构；旧快照即使数据修订相同也必须重新读取。
const SCHEMA = 2, MAX_ENTRIES = 12, MAX_BYTES = 512 * 1024, MAX_ENTRY_BYTES = 96 * 1024, MAX_AGE = 24 * 60 * 60 * 1000
const ACTIONS = new Set(['dashboard.get', 'catalog.get', 'accounts.list', 'categories.list', 'statistics.get', 'transactions.list'])
function actionOf(key) { return typeof key === 'string' ? key.slice(0, key.indexOf(':')) : '' }
function complete(action, value) {
  if (!validMetadata(value) || value.unchanged) return false
  if (action === 'dashboard.get') return Array.isArray(value.accounts) && value.summary && Array.isArray(value.recentTransactions)
  if (action === 'catalog.get') return Array.isArray(value.accounts) && Array.isArray(value.categories)
  if (action === 'statistics.get') return value.summary && Array.isArray(value.cashFlowTrend)
  if (action === 'transactions.list') return Array.isArray(value.transactions) && Object.prototype.hasOwnProperty.call(value, 'nextCursor')
  return Array.isArray(value[action === 'accounts.list' ? 'accounts' : 'categories'])
}
function createSnapshotStore(storage, now) {
  const io = storage || {
    get: key => wx.getStorageSync(key), set: (key, value) => wx.setStorageSync(key, value), remove: key => wx.removeStorageSync(key)
  }
  function eligible(entry, uid, size) {
    const action = actionOf(entry && entry.key)
    if (!ACTIONS.has(action) || !complete(action, entry.value) || entry.value.uid !== uid ||
      !Number.isFinite(entry.updatedAt) || entry.updatedAt > now() || now() - entry.updatedAt >= MAX_AGE || (size === undefined ? bytes(entry) : size) > MAX_ENTRY_BYTES) return false
    // Keys are generated by stableKey; reject malformed/oversized parameters instead of restoring partial content.
    const params = JSON.parse(entry.key.slice(action.length + 1))
    return params && typeof params === 'object' && !Array.isArray(params)
  }
  return {
    read(scope) {
      try {
        const raw = io.get(KEY)
        if (typeof raw !== 'string' || raw.length > MAX_BYTES || bytes(JSON.parse(raw)) > MAX_BYTES) return []
        const stored = JSON.parse(raw)
        if (stored.schema !== SCHEMA || stored.env !== scope.env || stored.uid !== scope.uid || !Array.isArray(stored.entries) || stored.entries.length > MAX_ENTRIES) return []
        let pages = 0
        return stored.entries.filter(entry => eligible(entry, scope.uid) && (actionOf(entry.key) !== 'transactions.list' || ++pages <= 3))
          .map(entry => ({ ...entry, policy: READ_POLICIES[actionOf(entry.key)] }))
      } catch (_) { return [] }
    },
    write(scope, entries) {
      try {
        const selected = [], stored = { schema: SCHEMA, env: scope.env, uid: scope.uid, entries: selected }
        let pages = 0, totalBytes = bytes(stored)
        for (const entry of entries.slice().reverse()) {
          if (!ACTIONS.has(actionOf(entry.key)) || (actionOf(entry.key) === 'transactions.list' && pages >= 3)) continue
          const size = bytes(entry), added = size + (selected.length ? 1 : 0)
          if (!eligible(entry, scope.uid, size) || totalBytes + added > MAX_BYTES) continue
          selected.unshift(entry); totalBytes += added
          if (actionOf(entry.key) === 'transactions.list') pages++
          if (selected.length >= MAX_ENTRIES) break
        }
        io.set(KEY, JSON.stringify(stored))
      } catch (_) { /* 缓存配额/存储故障不得改变正式写入结果。 */ }
    },
    clear() { try { io.remove(KEY) } catch (_) {} }
  }
}
module.exports = { createSnapshotStore, KEY, MAX_ENTRIES, MAX_BYTES, MAX_ENTRY_BYTES, MAX_AGE }
